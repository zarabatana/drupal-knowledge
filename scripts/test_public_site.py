# --- fixture L: canonical data changed without a rebuild is detected ----------

with tempfile.TemporaryDirectory() as tmp:
    copy = Path(tmp) / "repo"
    shutil.copytree(
        ROOT,
        copy,
        ignore=shutil.ignore_patterns(
            ".git", "dist", "__pycache__", ".venv", "evidence", "exchange", "feedback"
        ),
    )
    # A freshly copied repository is current.
    assert P.validate_public_dataset(copy) == ["PUBLIC_DATASET_CURRENT=PASS"]

    # Change one canonical record and publish nothing.
    target = copy / "security" / "advisories" / "SA-CORE-2025-001.json"
    mutated = dk_core.read_json(target)
    mutated["advisory"]["vulnerability_type"] = "Changed without republishing"
    target.write_text(json.dumps(mutated, indent=2) + "\n", encoding="utf-8")

    try:
        P.validate_public_dataset(copy)
    except dk_core.ValidationError as exc:
        assert "stale" in str(exc)
        assert "public-site/dataset" in str(exc)
        assert "public-site build" in str(exc)
    else:
        raise AssertionError("a changed canonical record left the dataset looking current")

    # Rebuilding makes it current again, and the identity has moved.
    before = MANIFEST["dataset_id"]
    P.write_dataset(copy)
    assert P.validate_public_dataset(copy) == ["PUBLIC_DATASET_CURRENT=PASS"]
    assert P.build_dataset(copy)[P.MANIFEST_FILE]["dataset_id"] != before
