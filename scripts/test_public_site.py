def flat(text: str) -> str:
    """Collapse whitespace so a phrase assertion survives HTML wrapping."""
    return " ".join(text.split())


def build_site(dataset: dict) -> dict[str, str]:
    """Render with fixed inputs so two calls are comparable."""
    root = ROOT / "public-site"
    editorial = {
        path.stem: path.read_text(encoding="utf-8").rstrip("\n")
        for path in sorted((root / "content").glob("*.html"))
    }
    assets = {
        path.name: path.read_text(encoding="utf-8")
        for path in sorted((root / "assets").iterdir())
        if path.is_file()
    }
    import dk as cli

    commands = [{"command": name, "help": ""} for name in cli.commands_for("community")]
    return R.render_site(
        dataset,
        editorial=editorial,
        assets=assets,
        commands=commands,
        built_at=FIXED_BUILD,
        today_ordinal=739_500,
        parse_day=lambda stamp: 739_400,
        commit="fixed",
    )


DATASET = P.build_dataset(ROOT)
