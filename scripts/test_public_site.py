assert "import dk_query" in export_source
for forbidden in ("json.load", "yaml", "glob(", "os.walk", "rglob"):
    assert forbidden not in export_source, forbidden
print("PUBLIC_SITE_REUSES_RELEASED_QUERY_LAYER=PASS")

# The renderer cannot reach canonical records at all: no query layer, no core,
# no repository root. It is structurally incapable of a second opinion.
# Parsed, not grepped: the docstring names the modules the renderer is kept away
# from, and prose about a boundary is not a breach of it.
render_imports = set()
for node in ast.walk(ast.parse(render_source)):
    if isinstance(node, ast.Import):
        render_imports.update(alias.name.split(".")[0] for alias in node.names)
    elif isinstance(node, ast.ImportFrom):
        render_imports.add((node.module or "").split(".")[0])
assert render_imports <= {"__future__", "html", "json", "pathlib", "typing"}, render_imports
for forbidden in ("open(", "read_text", "read_bytes", "Path(", "ROOT"):
    assert forbidden not in render_source, forbidden
assert "def render_site(" in render_source
print("PUBLIC_SITE_ARCHITECTURE_MINIMAL_AND_AUDITABLE=PASS")

# The export decides nothing about Drupal: no version comparison, no severity,
# no applicability, no ranking of its own.
for forbidden in (
    "def score_record", "def evaluate", "def applies", "severity",
    "affected_versions =", "def compare_version", "cvss",
):
    assert forbidden not in export_source.lower(), forbidden
# Ranking is imported from the released layer, not rewritten here.
assert "query.score_record(" in export_source
assert "def score" not in export_source
print("PUBLIC_EXPORT_CONTAINS_NO_SECOND_SEMANTIC_ENGINE=PASS")

# No HTTP server, no request handling, no route dispatch: this is a build.
