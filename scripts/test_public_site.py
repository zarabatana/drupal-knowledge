#!/usr/bin/env python3
"""What the public website is allowed to say, and what it must not imply.

A website is a different risk from a CLI. Nobody installs it, nobody reads its
help text, and a page is often the only thing a developer ever sees. Two
failures matter more here than anywhere else in this repository.

The first is a second opinion. If the site interpreted canonical records itself,
it could disagree with the command line and nothing would notice. The tests
below hold the pipeline in one direction — records, released query layer, public
dataset, pages — and prove the renderer cannot see past the dataset.

The second is publishing what was never meant to be public. Project evidence,
findings, discovery signals and anything carrying a local path or a project
name are excluded by name, and the generated bytes are scanned rather than
trusted.

Everything here is hermetic: canonical local records only, no network, and the
stale-guard fixture works on a copy so no test can leave the repository dirty.
"""

